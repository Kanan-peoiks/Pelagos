// Widens the `as const` literal string types (e.g. "About") down to `string`
// (while preserving function signatures like `(n: number) => string`) so
// this type describes the *shape* shared by every language, not just en's
// exact literals — otherwise passing the az dictionary anywhere a function
// expects `Translations` fails type-checking even though the shape matches.
type Widen<T> = T extends (...args: infer A) => infer R
  ? (...args: A) => R
  : T extends string
    ? string
    : { [K in keyof T]: Widen<T[K]> };

export type Translations = Widen<typeof translations.en>;
